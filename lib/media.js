/**
 * Local media helpers: MIME detection, image encoding for chat requests, and
 * writing generated binaries into the configured output directory.
 */

import { mkdir, readFile, writeFile } from 'node:fs/promises'
import path from 'node:path'

const MIME_BY_EXTENSION = new Map(Object.entries({
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.webp': 'image/webp',
  '.gif': 'image/gif',
  '.bmp': 'image/bmp',
  '.heic': 'image/heic',
  '.mp3': 'audio/mpeg',
  '.wav': 'audio/wav',
  '.m4a': 'audio/mp4',
  '.ogg': 'audio/ogg',
  '.flac': 'audio/flac',
  '.mp4': 'video/mp4',
  '.mov': 'video/quicktime',
  '.webm': 'video/webm',
}))

/** MIME type from a file name, with a generic binary fallback. */
export function mimeOf(filePath) {
  return MIME_BY_EXTENSION.get(path.extname(filePath).toLowerCase()) ?? 'application/octet-stream'
}

/** Whether a reference is already usable as a remote or inline URL. */
function isInlineReference(reference) {
  return /^data:/iu.test(reference) || /^https?:\/\//iu.test(reference)
}

/**
 * Convert one image reference into a form the vision endpoint accepts.
 * @param reference - an absolute local path, an `http(s)` URL, or a `data:` URI.
 * @returns a URL string; local files become base64 data URIs.
 */
export async function imageReference(reference) {
  if (isInlineReference(reference)) return reference
  const filePath = path.resolve(reference)
  const bytes = await readFile(filePath)
  return `data:${mimeOf(filePath)};base64,${bytes.toString('base64')}`
}

/** Read a local binary for multipart upload. */
export async function readBinary(reference) {
  return readFile(path.resolve(reference))
}

/** Read a local file as a Blob with the MIME type its extension implies. */
export async function readBlob(reference) {
  const filePath = path.resolve(reference)
  const bytes = await readFile(filePath)
  return new Blob([bytes], { type: mimeOf(filePath) })
}

/** Local base name for a generated artifact, keeping directories inside the output root. */
function baseNameOf(reference, fallback) {
  const name = typeof reference === 'string' && reference.trim().length > 0
    ? path.basename(reference.trim())
    : fallback
  const stem = name.replace(/\.[^.]+$/u, '')
  return stem.length > 0 ? stem.replace(/[^\w.-]+/gu, '_').slice(0, 60) : fallback
}

/**
 * Persist generated bytes and return the absolute path.
 * @param outputDir - directory that receives the artifact.
 * @param bytes - complete file content.
 * @param options - suffix such as `.mp4`, a source name to derive the stem
 *   from, and a timestamp-free counter so repeated calls do not collide.
 */
export async function saveArtifact(outputDir, bytes, options) {
  const { extension, sourceName, fallbackName = 'artifact' } = options
  await mkdir(outputDir, { recursive: true })
  const stamp = new Date().toISOString().replace(/[:.]/gu, '-')
  const stem = baseNameOf(sourceName, fallbackName)
  const filePath = path.join(outputDir, `${stem}-${stamp}${extension}`)
  await writeFile(filePath, bytes)
  return filePath
}

/** Element/array content of one chat completion response, flattened to text. */
export function completionText(payload) {
  const choice = payload?.choices?.[0]
  const content = choice?.message?.content ?? choice?.text
  if (typeof content === 'string') return content
  if (Array.isArray(content)) {
    const parts = content
      .map((part) => {
        if (typeof part === 'string') return part
        if (typeof part?.text === 'string') return part.text
        return ''
      })
      .filter((part) => part.length > 0)
    if (parts.length > 0) return parts.join('\n')
  }
  if (typeof payload?.output_text === 'string') return payload.output_text
  return ''
}

/** Extension for a generated artifact, from a MIME type or a requested format. */
export function extensionFor(mimeType, requestedFormat, fallback) {
  if (typeof requestedFormat === 'string' && /^[a-z0-9]{2,5}$/iu.test(requestedFormat)) {
    return `.${requestedFormat.toLowerCase()}`
  }
  const known = {
    'audio/mpeg': '.mp3',
    'audio/wav': '.wav',
    'audio/ogg': '.ogg',
    'video/mp4': '.mp4',
    'video/webm': '.webm',
  }[String(mimeType ?? '').split(';')[0].trim().toLowerCase()]
  return known ?? fallback
}
